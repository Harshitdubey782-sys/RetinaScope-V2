def add_report_header(story, styles, dual=False):
    subtitle = (
        "Dual-Eye Diabetic Retinopathy Screening Report"
        if dual else
        "Diabetic Retinopathy Screening Report"
    )

    story.extend([
        Paragraph("RETINASCOPE", styles["title"]),
        Paragraph(subtitle, styles["subtitle"]),
        HRFlowable(
            width="100%",
            thickness=1,
            color=colors.HexColor("#CBD5E1")
        ),
        Spacer(1, 5)
    ])


def add_model_information(story, styles):
    story.extend([
        Paragraph("5. Model Information", styles["section"]),
        Paragraph(
            "Model: EfficientNet-B0 &nbsp;|&nbsp; "
            "Task: 5-class DR classification &nbsp;|&nbsp; "
            "Training dataset: APTOS 2019 &nbsp;|&nbsp; "
            "Explainability: Grad-CAM",
            styles["body"]
        ),
        Spacer(1, 4),
        Paragraph(
            "Checkpoint validation reference: "
            "80.08% accuracy and 0.6486 macro F1. "
            "These are internal validation results, not a guarantee "
            "of performance on an individual patient.",
            styles["body"]
        )
    ])


def add_disclaimer(story, styles):
    story.extend([
        Spacer(1, 7),
        HRFlowable(
            width="100%",
            thickness=0.7,
            color=colors.HexColor("#CBD5E1")
        ),
        Spacer(1, 5),
        Paragraph(
            "<b>IMPORTANT:</b> RetinaScope is a research and "
            "demonstration prototype. This AI-assisted screening "
            "output is not a standalone clinical diagnosis and "
            "should not replace evaluation by a qualified "
            "healthcare professional. Reported performance is "
            "based on an internal validation split and does not "
            "establish clinical validity.",
            styles["small"]
        ),
        Spacer(1, 5),
        Paragraph(
            "Generated by RetinaScope · Explainable AI for "
            "Diabetic Retinopathy Screening",
            styles["small"]
        )
    ])


def probability_table(probabilities, dual_probabilities=None):
    rows = (
        [["Severity", "Right Eye", "Left Eye"]]
        if dual_probabilities is not None
        else [["Severity", "Probability"]]
    )

    for i in range(5):
        label = f"Grade {i} — {CLASS_NAMES[i]}"

        if dual_probabilities is None:
            value = float(probabilities[0, i]) * 100
            rows.append([label, f"{value:.2f}%"])
        else:
            right_value = float(probabilities[0, i]) * 100
            left_value = float(dual_probabilities[0, i]) * 100

            rows.append([
                label,
                f"{right_value:.2f}%",
                f"{left_value:.2f}%"
            ])

    if dual_probabilities is None:
        widths = [125 * mm, 53 * mm]
    else:
        widths = [95 * mm, 41 * mm, 41 * mm]

    return Table(
        rows,
        colWidths=widths,
        style=TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E2E8F0")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
            ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4)
        ])
    )


