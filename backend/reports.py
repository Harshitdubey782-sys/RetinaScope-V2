# SINGLE-EYE SCREENING REPORT
# ============================================================

def generate_screening_report(
    patient,
    original_image,
    heatmap,
    probabilities,
    predicted_class,
    confidence
):
    """Generate a single-eye screening PDF in memory."""

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=15 * mm,
        leftMargin=15 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="RetinaScope Patient Screening Report",
        author="RetinaScope"
    )

    styles = get_report_styles()
    story = []

    add_report_header(story, styles)

    # Patient information
    patient_rows = [
        ["Case ID", patient["Case ID"], "Screening Date", patient["Screening Date"]],
        ["Patient Name", patient["Patient Name"], "Age", patient["Age"]],
        ["Sex", patient["Sex"], "Screening Centre", patient["Screening Centre"]],
        ["Eye Examined", patient["Eye Examined"], "Image ID", patient["Image ID"]],
        ["Diabetes Type", patient["Diabetes Type"], "Duration", patient["Diabetes Duration"]],
        ["Previous DR", patient["Previous DR"], "Previous Eye Exam", patient["Previous Eye Exam"]]
    ]

    story.extend([
        Paragraph("1. Patient Information", styles["section"]),
        Table(
            patient_rows,
            colWidths=[30 * mm, 57 * mm, 34 * mm, 57 * mm],
            style=patient_table_style()
        )
    ])

    # AI screening result
    referable = predicted_class >= 2

    status = "REFERABLE DR" if referable else "NON-REFERABLE"

    status_color = (
        "#DC2626" if referable else "#16A34A"
    )

    recommendation = (
        "Further evaluation by a qualified eye-care professional is recommended."
        if referable else
        "Routine screening / follow-up according to appropriate clinical guidance."
    )

    result_table = Table(
        [
            ["Predicted Grade", f"Grade {predicted_class} — {CLASS_NAMES[predicted_class]}"],
            ["Model Confidence", f"{confidence * 100:.2f}%"],
            ["Screening Status", status],
            ["Screening Recommendation", recommendation]
        ],
        colWidths=[48 * mm, 130 * mm],
        style=TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F1F5F9")),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTNAME", (1, 0), (1, -1), "Helvetica"),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#334155")),
            ("TEXTCOLOR", (1, 2), (1, 2), colors.HexColor(status_color)),
            ("FONTNAME", (1, 2), (1, 2), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6)
        ])
    )

    story.extend([
        Paragraph("2. AI Screening Result", styles["section"]),
        result_table
    ])

    # Explainability images
    original_buffer = image_to_buffer(original_image)
    heatmap_buffer = image_to_buffer(heatmap)

    story.extend([
        Paragraph("3. Explainability", styles["section"]),
        Table(
            [
                [
                    RLImage(original_buffer, width=82 * mm, height=62 * mm),
                    RLImage(heatmap_buffer, width=82 * mm, height=62 * mm)
                ],
                [
                    Paragraph("<b>Original Fundus Image</b>", styles["small"]),
                    Paragraph("<b>Grad-CAM Attention</b>", styles["small"])
                ]
            ],
            colWidths=[89 * mm, 89 * mm],
            style=TableStyle([
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("BOX", (0, 0), (-1, -2), 0.5, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -2), 0.4, colors.HexColor("#E2E8F0")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4)
            ])
        ),
        Paragraph(
            "Grad-CAM highlights image regions that contributed "
            "to the selected model prediction. It represents model "
            "attention and is not a confirmed lesion map.",
            styles["small"]
        ),
        Paragraph("4. Class Probability Distribution", styles["section"]),
        probability_table(probabilities)
    ])

    add_model_information(story, styles)
    add_disclaimer(story, styles)

    doc.build(story)

    buffer.seek(0)
    return buffer.getvalue()


