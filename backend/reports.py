# DUAL-EYE SCREENING REPORT
# ============================================================

def generate_dual_eye_report(patient, right_data, left_data):
    """Generate a bilateral screening PDF in memory."""

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=15 * mm,
        leftMargin=15 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="RetinaScope Dual-Eye Screening Report",
        author="RetinaScope"
    )

    styles = get_report_styles()
    story = []

    add_report_header(story, styles, dual=True)

    # Patient information
    patient_rows = [
        ["Case ID", patient["Case ID"], "Screening Date", patient["Screening Date"]],
        ["Patient Name", patient["Patient Name"], "Age", patient["Age"]],
        ["Sex", patient["Sex"], "Screening Centre", patient["Screening Centre"]],
        ["Eye Examined", "Both", "Right Image ID", patient["Right Image ID"]],
        ["Diabetes Type", patient["Diabetes Type"], "Left Image ID", patient["Left Image ID"]],
        ["Duration", patient["Diabetes Duration"], "Previous DR", patient["Previous DR"]],
        ["Previous Eye Exam", patient["Previous Eye Exam"], "", ""]
    ]

    story.extend([
        Paragraph("1. Patient Information", styles["section"]),
        Table(
            patient_rows,
            colWidths=[30 * mm, 57 * mm, 34 * mm, 57 * mm],
            style=patient_table_style()
        )
    ])

    # Bilateral results
    def eye_result(data):
        pred = data["predicted_class"]

        return (
            f"Grade {pred} — {CLASS_NAMES[pred]}",
            f"{data['confidence'] * 100:.2f}%",
            "REFERABLE DR" if pred >= 2 else "NON-REFERABLE"
        )

    right_result = eye_result(right_data)
    left_result = eye_result(left_data)

    story.extend([
        Paragraph(
            "2. AI Screening Result — Right vs Left Eye",
            styles["section"]
        ),
        Table(
            [
                ["", "Right Eye", "Left Eye"],
                ["Predicted Grade", right_result[0], left_result[0]],
                ["Model Confidence", right_result[1], left_result[1]],
                ["Screening Status", right_result[2], left_result[2]]
            ],
            colWidths=[55 * mm, 62 * mm, 62 * mm],
            style=TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E2E8F0")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTNAME", (0, 1), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6)
            ])
        ),
        Spacer(1, 5),
        Paragraph(
            "Inter-eye severity comparison describes the two AI "
            "screening outputs. It is not a clinical assessment "
            "of disease asymmetry.",
            styles["small"]
        )
    ])

    # Original images and Grad-CAM
    right_original = image_to_buffer(right_data["image"])
    left_original = image_to_buffer(left_data["image"])

    right_heatmap = image_to_buffer(right_data["heatmap"])
    left_heatmap = image_to_buffer(left_data["heatmap"])

    story.extend([
        Paragraph("3. Dual-Eye Explainability", styles["section"]),
        Table(
            [
                [
                    Paragraph("<b>Right Eye</b>", styles["small"]),
                    Paragraph("<b>Left Eye</b>", styles["small"])
                ],
                [
                    RLImage(right_original, width=76 * mm, height=57 * mm),
                    RLImage(left_original, width=76 * mm, height=57 * mm)
                ],
                [
                    RLImage(right_heatmap, width=76 * mm, height=57 * mm),
                    RLImage(left_heatmap, width=76 * mm, height=57 * mm)
                ],
                [
                    Paragraph("Original Fundus", styles["small"]),
                    Paragraph("Original Fundus", styles["small"])
                ],
                [
                    Paragraph("Grad-CAM Attention", styles["small"]),
                    Paragraph("Grad-CAM Attention", styles["small"])
                ]
            ],
            colWidths=[89 * mm, 89 * mm],
            style=TableStyle([
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E2E8F0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4)
            ])
        ),
        Paragraph(
            "Grad-CAM highlights regions that contributed to each "
            "selected prediction. Highlighted regions represent "
            "model attention, not confirmed lesions.",
            styles["small"]
        ),
        Paragraph("4. Class Probability Comparison", styles["section"]),
        probability_table(
            right_data["probabilities"],
            left_data["probabilities"]
        )
    ])

    add_model_information(story, styles)
    add_disclaimer(story, styles)

    doc.build(story)

    buffer.seek(0)
    return buffer.getvalue()
